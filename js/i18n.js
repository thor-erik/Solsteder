function _browserLang() {
  const nav = (navigator.language || 'no').toLowerCase();
  if (nav.startsWith('sv')) return 'se';
  if (nav.startsWith('da')) return 'dk';
  if (nav.startsWith('nb') || nav.startsWith('nn') || nav.startsWith('no')) return 'no';
  if (nav.startsWith('en')) return 'en';
  return 'no';
}
function prefLang()     { return localStorage.getItem('pref_lang') || _browserLang(); }
function prefTempUnit() { return localStorage.getItem('pref_temp') || 'C'; }

function setPrefLang(l) {
  localStorage.setItem('pref_lang', l);
  const inp = document.getElementById('venue-search');
  if (inp) inp.placeholder = t('search_placeholder');
  if (typeof _renderProfilePanel === 'function') _renderProfilePanel();
  if (typeof update === 'function') update();
}

function setPrefTempUnit(u) {
  localStorage.setItem('pref_temp', u);
  if (typeof _renderProfilePanel === 'function') _renderProfilePanel();
  if (typeof update === 'function') update();
}

/**
 * Translate a key. Optional vars object replaces {name} placeholders.
 * Example: t('opens_at', { time: '14:00' }) → 'Opens 14:00' / 'Åpner 14:00'
 */
function t(key, vars) {
  const lang = prefLang();
  let str = (_STRINGS[lang] || _STRINGS.no)[key] ?? _STRINGS.en[key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) str = str.replaceAll(`{${k}}`, v);
  return str;
}

/**
 * Translate an array-valued key (e.g. days_short, months_long).
 * Returns the array for the current language, falling back to English.
 */
function tA(key) {
  const lang = prefLang();
  return (_STRINGS[lang] || _STRINGS.no)[key] ?? _STRINGS.en[key] ?? [];
}

/** Format a temperature in °C into the user's preferred unit. */
function formatTemp(celsius) {
  if (celsius == null) return '—';
  if (prefTempUnit() === 'F') return `${Math.round(celsius * 9 / 5 + 32)}°F`;
  return `${celsius}°`;
}
